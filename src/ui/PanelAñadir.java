    // cn este se sube la foto del libro 
    private void btnAgregarFotoActionPerformed(java.awt.event.ActionEvent evt)
    {
        JFileChooser selector = new JFileChooser();
        javax.swing.filechooser.FileNameExtensionFilter filtro
                = new javax.swing.filechooser.FileNameExtensionFilter("Imágenes", "jpg", "png");
        selector.setFileFilter(filtro);

        int resultado = selector.showOpenDialog(this);

        if (resultado == JFileChooser.APPROVE_OPTION)
        {
            java.io.File archivo = selector.getSelectedFile();
            rutaImagen = archivo.getAbsolutePath(); // guardamos ruta

            try
            {
                ImageIcon icon = new ImageIcon(rutaImagen);
                Icon icono = new ImageIcon(
                        icon.getImage().getScaledInstance(
                                lblFoto.getWidth(),
                                lblFoto.getHeight(),
                                Image.SCALE_SMOOTH
                        )
                );
                lblFoto.setIcon(icono);
            } catch (Exception e)
            {
                JOptionPane.showMessageDialog(this, "Error al cargar imagen");
            }
        }
    }

