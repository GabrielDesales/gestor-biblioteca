    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt)
    {
        //Pregunta si el usuario quiere cancelar la acción
        int resultado = JOptionPane.showConfirmDialog(this, "¿Está seguro de cancelar esta acción?",
                "Cancelar", JOptionPane.YES_NO_OPTION);
        //Si el resultado es sí (0), limpia los campos, cierra el formulario y abre la página principal
        if (resultado == 0)
        {
            //Limpiar campos
            limpiarCampos();
        }
    }

    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt)
    {
        // 1. Captura y limpieza de datos
        String titulo = nomT.getText().trim();
        String autor = autorT.getText().trim();
        String isbn = isbnT.getText().trim();
        String categoria = catT.getText().trim();
        String ani = anioT.getText().trim();
        int anioInt;

        // Quita los guiones para validación interna si es necesario
        String isbnSinGuion = isbn.replace("-", "").replace(" ", "");

        // 2. Validaciones preventivas (Campos vacíos)
        if (titulo.isEmpty() || autor.isEmpty() || isbn.isEmpty()
                || categoria.isEmpty() || ani.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Completa todos los campos");
            return;
        }

        // 3. Validación de formato
        try
        {
            anioInt = Integer.parseInt(ani);
            if (ani.length() != 4)
            {
                JOptionPane.showMessageDialog(this, "El año debe tener un formato de 4 dígitos");
                return;
            }
            if (isbnSinGuion.length() != 13)
            {
                JOptionPane.showMessageDialog(this, "El ISBN debe contener 13 dígitos");
                return;
            }
        } catch (NumberFormatException e)
        {
            JOptionPane.showMessageDialog(this, "Año inválido", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // --- CRUCIAL: EL CAMBIO LÓGICO ESTÁ AQUÍ ---

        // 4. PRIMERO verificamos si el ISBN ya existe en la lista
        // Usamos el método validarIsbn que ya tienes definido en tu clase de estructura de datos
        if (this.obj.validarIsbn(isbn) == 1) 
        {
            JOptionPane.showMessageDialog(this, "Error: El ISBN " + isbn + " ya está registrado.");
            isbnT.requestFocus(); // Ponemos el foco en el campo para que el usuario lo corrija
            return; // Salimos del método SIN insertar nada
        }

        // 5. SI NO EXISTE, procedemos a insertar el nuevo libro
        if (this.obj.listaVacia())
        {
            this.obj.insertarPrimero(titulo, autor, isbn, categoria, anioInt, rutaImagen);
        } else
        {
            this.obj.insertarUltimo(titulo, autor, isbn, categoria, anioInt, rutaImagen);
        }

        // 6. Mensaje de éxito y navegación
        JOptionPane.showMessageDialog(this, "El libro se agregó correctamente");
        limpiarCampos();
    
    int resp = JOptionPane.showConfirmDialog(this, "¿Desea agregar otro libro?", 
                                           "Confirmación", JOptionPane.YES_NO_OPTION);
    
    
    limpiarCampos();

}
        


